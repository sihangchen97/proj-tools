"""C6: `proj compact` — rewrite `.proj/events.jsonl` as one `snapshot` event per
record + one project-level snapshot (the state of the current cache), verified
by a full replay before the file is replaced.

The compacted log is *equivalent* to the original: replaying it reproduces the
exact same cache (checked table-by-table before the swap). It is NOT a business
repair — if a merge left a P3 / gate inconsistency, `proj check` still reports
it; compact only shrinks the log (hard-parts C6).
"""
from __future__ import annotations

import json
import subprocess
import tempfile
from pathlib import Path

from proj import events as ev
from proj import replay as rp
from proj.core import db as dbmod
from proj.core import fsio
from proj.core.config import ProjConfig, reporter
from proj.engine import store as rec

# the tables that define the project state (records is the single shared table;
# `meta` is compared below with the incremental `ev:*` bookkeeping stripped).
_DATA_TABLES = ("records", "record_changelog", "items", "relations",
                "wip_entries", "changelog_entries")


def events_path(cfg: ProjConfig) -> Path:
    return cfg.root / ".proj" / "events.jsonl"


def _git(root: Path, *args: str) -> tuple[str, int]:
    p = subprocess.run(["git", "-C", str(root), *args], check=False,
                       capture_output=True, text=True)
    return p.stdout + p.stderr, p.returncode


def _precheck(cfg: ProjConfig) -> str | None:
    """C6 preconditions. Return an error message, or None if compact may run."""
    gdot = cfg.root / ".git"
    if (gdot / "MERGE_HEAD").exists() or (gdot / "REBASE_HEAD").exists():
        return "a merge or rebase is in progress — resolve it first, then compact"
    out, rc = _git(cfg.root, "status", "--porcelain")
    if rc == 0 and out.strip():
        lines = out.strip().splitlines()
        more = f" (+{len(lines) - 1} more)" if len(lines) > 1 else ""
        return (f"the working tree is not clean — commit or stash first: "
                f"{lines[0]}{more}")
    return None


# the columns that make a row *content* (not insertion order): every table with
# an autoincrement `INTEGER PRIMARY KEY id` (record_changelog,
# changelog_entries) drops that id — a replay re-inserts in a different order,
# so the id is never comparable; wip_entries.added_at is regenerated by a
# snapshot (it only remembers wip + source), like the `ev:*` meta.
_SELECT: dict[str, str] = {
    "records": ("SELECT id, type, title, status, summary, \"commit\", created, "
                "sections FROM records ORDER BY id"),
    "record_changelog": ("SELECT record_id, date, category, message, status, actor, id "
                          "FROM record_changelog ORDER BY record_id, date, id"),
    "items": ("SELECT record_id, no, pos, text, state, note, owner, due, "
              "\"commit\", trailer, created, closed_at, deleted, section, task, "
              "uuid FROM items ORDER BY record_id, no"),
    "relations": "SELECT * FROM relations ORDER BY source, target, kind",
    "wip_entries": ("SELECT record_id, pos, source FROM wip_entries "
                    "ORDER BY record_id"),
    "changelog_entries": ("SELECT version, category, message, date FROM "
                          "changelog_entries ORDER BY version, category, message, date"),
}


def _norm(s: str) -> str:
    """records.sections is a JSON string — key order is semantically irrelevant
    (write path: template order, replayer: event order); normalize for compare."""
    if not s or s == "{}":
        return s
    return json.dumps(json.loads(s), sort_keys=True, ensure_ascii=False)


def _dump(db: dbmod.Db) -> dict:
    """The project state as comparable rows (content only, see `_SELECT`); meta
    keeps only real state — the incremental `ev:*` (C3) and F1/F2 `fp:*`
    fingerprint bookkeeping are dropped (a replay does not carry either).
    C2: records.sections is normalized (JSON key order is not data)."""
    out = {t: [tuple(r) for r in db.conn.execute(q)]
           for t, q in _SELECT.items()}
    out["records"] = [tuple(_norm(r[7]) if i == 7 else r[i]
                           for i in range(8)) for r in out["records"]]
    out["meta"] = [tuple(r) for r in db.conn.execute(
        "SELECT * FROM meta WHERE key NOT LIKE 'ev:%' AND key NOT LIKE 'fp:%' "
        "ORDER BY key")]
    return out


def run_compact(cfg: ProjConfig) -> tuple[list[str], list[str]]:
    """C6: shrink events.jsonl to the current state as snapshots. Returns
    (problems, notes); on problems the file is left untouched."""
    notes: list[str] = []
    err = _precheck(cfg)
    if err:
        return [err], notes
    path = events_path(cfg)
    if not path.is_file():
        return [], ["no events.jsonl yet — nothing to compact"]
    try:
        orig = ev.read(path)
    except ValueError as e:
        return [f"events.jsonl is unreadable ({e}) — run `proj check` first"], notes
    if not orig:
        return [], ["events.jsonl is empty — nothing to compact"]

    specs = rec.load_registry(cfg.root)
    with fsio.project_lock(cfg.root, "proj compact"):
        with rec.open_db(cfg) as db:
            # the snapshots sort at the end of the log: the original max `at`
            snaps = rp.snapshot_events(db, at=max(e["at"] for e in orig),
                                       actor=reporter())
            before = _dump(db)
        # rebuild the snapshots into a throwaway db and compare with the cache
        with tempfile.TemporaryDirectory() as td:
            fresh = dbmod.Db(Path(td) / "compact.sqlite")
            try:
                res = rp.replay(fresh, snaps, specs)
                after = _dump(fresh)
            finally:
                fresh.close()
        if res.diagnostics:
            return ([f"replaying the snapshots reports problems: "
                     f"{'; '.join(res.diagnostics[:3])}"], notes)
        if before != after:
            diff = ", ".join(k for k in before if before[k] != after[k])
            return ([f"the compacted log would NOT reproduce the current DB "
                     f"(tables differ: {diff}) — not replaced"], notes)
        # verified: atomically replace the log (temp file + os.replace)
        text = "".join(ev.to_line(e) for e in sorted(snaps, key=ev.sort_key))
        fsio.write_atomic(path, text)
    return [], [f"compacted {len(orig)} event(s) into {len(snaps)} snapshot(s); "
                f"commit this change on its own and ask collaborators to sync "
                f"first (their next replay picks up the snapshots)"]
